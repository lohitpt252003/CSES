template <typename T>
T modpow(T a, T b, T m) {
    T ans = 1 % m;
    a %= m;

    while (b > 0) {
        if (b & 1) ans = (ans * a) % m;
        a = (a * a) % m;
        b >>= 1;
    }

    return ans;
}


template <typename T>
T pow(T a, T b) {
    T ans = 1;

    while (b > 0) {
        if (b & 1) ans = ans * a;
        a = a * a;
        b >>= 1;
    }

    return ans;
}


template <typename T>
T is_square(T __x) {
    T _x = sqrt((long double) __x);

    return _x * _x == __x;
}


struct Mint {
    ll val;
    
    Mint(ll v = 0) {
        val = v % MOD;
        if (val < 0) val += MOD;
    }

    Mint& operator+=(const Mint& other) { val = (val + other.val) % MOD; return *this; }
    Mint& operator-=(const Mint& other) { val = (val - other.val + MOD) % MOD; return *this; }
    Mint& operator*=(const Mint& other) { val = (val * other.val) % MOD; return *this; }
    Mint& operator/=(const Mint& other) { return *this *= other.inv(); }

    friend Mint operator+(Mint a, const Mint& b) { return a += b; }
    friend Mint operator-(Mint a, const Mint& b) { return a -= b; }
    friend Mint operator*(Mint a, const Mint& b) { return a *= b; }
    friend Mint operator/(Mint a, const Mint& b) { return a /= b; }
    friend bool operator==(const Mint& a, const Mint& b) { return a.val == b.val; }
    friend bool operator!=(const Mint& a, const Mint& b) { return a.val != b.val; }

    Mint power(ll p) const {
        Mint res = 1, base = *this;
        while (p > 0) {
            if (p % 2 == 1) res *= base;
            base *= base;
            p /= 2;
        }
        return res;
    }

    Mint inv() const { return power(MOD - 2); }

    friend istream& operator>>(istream& is, Mint& m) { ll v; is >> v; m = Mint(v); return is; }
    friend ostream& operator<<(ostream& os, const Mint& m) { return os << m.val; }

    inline static vector<Mint> fact, invFact;

    static void precompute(int n) {
        fact.assign(n + 1, 1);
        invFact.assign(n + 1, 1);
        for (int i = 1; i <= n; i++) {
            fact[i] = fact[i - 1] * i;
        }
        invFact[n] = fact[n].inv();
        for (int i = n - 1; i >= 0; i--) {
            invFact[i] = invFact[i + 1] * (i + 1);
        }
    }

    static Mint nCr(int n, int r) {
        if (r < 0 or r > n or n < 0) return 0;
        if (n >= (int) fact.size()) precompute(n * 2); 
        return fact[n] * invFact[r] * invFact[n - r];
    }

    static Mint nPr(int n, int r) {
        if (r < 0 or r > n or n < 0) return 0;
        if (n >= (int) fact.size()) precompute(n * 2);
        return fact[n] * invFact[n - r];
    }
};

void precompute(int n) { Mint::precompute(n); }
Mint nCr(int n, int r) { return Mint::nCr(n, r); }
Mint nPr(int n, int r) { return Mint::nPr(n, r); }



class Prime {
private:
    int max_limit;

public:
    vector<bool> is_prime;
    vector<int> primes;

    Prime(int limit, bool store_sieve = true, bool store_primes = false) {
        max_limit = limit;
        if (store_sieve or store_primes) build_sieve(store_sieve, store_primes);
    }


    void build_sieve(bool store_sieve, bool store_primes) {
        vector<bool> sieve(max_limit + 1, true);
        sieve[0] = sieve[1] = false;

        for (int p = 2; p * p <= max_limit; p++) {
            if (sieve[p]) for (int i = p * p; i <= max_limit; i += p) sieve[i] = false;
        }

        if (store_primes) for (int p = 2; p <= max_limit; p++) if (sieve[p]) primes.push_back(p);

        if (store_sieve) is_prime = std::move(sieve);
    }

    bool check_prime(long long n) const {
        if (!is_prime.empty() and n <= max_limit) return is_prime[n];
        if (n < 2) return false;
        if (n == 2 or n == 3) return true;
        if (n % 2 == 0 or n % 3 == 0) return false;

        
        for (long long i = 5; i * i <= n; i += 6) if (n % i == 0 or n % (i + 2) == 0) return false;

        return true;
    }

    static bool is_prime_standalone(long long n) {
        if (n < 2) return false;
        if (n == 2 or n == 3) return true;
        if (n % 2 == 0 or n % 3 == 0) return false;

        for (long long i = 5; i * i <= n; i += 6) if (n % i == 0 or n % (i + 2) == 0) return false;

        return true;
    }
};


template <typename T>
class StaticPrefixArray {
public:
    vector<T> pref_sum;
    vector<T> pref_xor;

    StaticPrefixArray(const vector<T>& a, bool enable_sum = true, bool enable_xor = false) {
        int n = a.size();
        
        if (enable_sum) pref_sum.assign(n, 0);
        if (enable_xor) pref_xor.assign(n, 0);

        for (int i = 0; i < n; i++) {
            if (enable_sum) pref_sum[i] = (i > 0 ? pref_sum[i - 1] : 0) + a[i];
            if (enable_xor) pref_xor[i] = (i > 0 ? pref_xor[i - 1] : 0) ^ a[i];
        }
    }

    T querySum(int l, int r) const {
        if (pref_sum.empty() || l > r || l < 0 || r >= (int)pref_sum.size()) return 0;
        return pref_sum[r] - (l > 0 ? pref_sum[l - 1] : 0);
    }

    T queryXor(int l, int r) const {
        if (pref_xor.empty() || l > r || l < 0 || r >= (int)pref_xor.size()) return 0;
        return pref_xor[r] ^ (l > 0 ? pref_xor[l - 1] : 0);
    }
};


template <typename T>
class SparseTable {
private:
    static T custom_gcd(T a, T b) {
        while (b) {
            a %= b;
            std::swap(a, b);
        }
        return a;
    }
    
    static T custom_lcm(T a, T b) {
        if (a == 0 || b == 0) return 0;
        return (a / custom_gcd(a, b)) * b;
    }

public:
    int n, log_max;
    std::vector<int> bin_log;
    std::vector<std::vector<T>> st_min, st_max, st_gcd, st_lcm, st_and, st_or;

    SparseTable(const std::vector<T>& a, bool enable_min = true, bool enable_max = false, 
                bool enable_gcd = false, bool enable_lcm = false, 
                bool enable_and = false, bool enable_or = false) {
        n = a.size();
        if (n == 0) return;
        
        bin_log.assign(n + 1, 0);
        for (int i = 2; i <= n; i++) bin_log[i] = bin_log[i / 2] + 1;
        
        log_max = bin_log[n] + 1;
        
        if (enable_min) { st_min.assign(log_max, std::vector<T>(n)); for (int i = 0; i < n; i++) st_min[0][i] = a[i]; }
        if (enable_max) { st_max.assign(log_max, std::vector<T>(n)); for (int i = 0; i < n; i++) st_max[0][i] = a[i]; }
        if (enable_gcd) { st_gcd.assign(log_max, std::vector<T>(n)); for (int i = 0; i < n; i++) st_gcd[0][i] = a[i]; }
        if (enable_lcm) { st_lcm.assign(log_max, std::vector<T>(n)); for (int i = 0; i < n; i++) st_lcm[0][i] = a[i]; }
        if (enable_and) { st_and.assign(log_max, std::vector<T>(n)); for (int i = 0; i < n; i++) st_and[0][i] = a[i]; }
        if (enable_or)  { st_or.assign(log_max, std::vector<T>(n));  for (int i = 0; i < n; i++) st_or[0][i] = a[i]; }

        for (int j = 1; j < log_max; j++) {
            for (int i = 0; i + (1 << j) <= n; i++) {
                if (enable_min) st_min[j][i] = std::min(st_min[j - 1][i], st_min[j - 1][i + (1 << (j - 1))]);
                if (enable_max) st_max[j][i] = std::max(st_max[j - 1][i], st_max[j - 1][i + (1 << (j - 1))]);
                if (enable_gcd) st_gcd[j][i] = custom_gcd(st_gcd[j - 1][i], st_gcd[j - 1][i + (1 << (j - 1))]);
                if (enable_lcm) st_lcm[j][i] = custom_lcm(st_lcm[j - 1][i], st_lcm[j - 1][i + (1 << (j - 1))]);
                if (enable_and) st_and[j][i] = st_and[j - 1][i] & st_and[j - 1][i + (1 << (j - 1))];
                if (enable_or)  st_or[j][i]  = st_or[j - 1][i] | st_or[j - 1][i + (1 << (j - 1))];
            }
        }
    }

    T queryMin(int l, int r) const {
        if (st_min.empty() || l > r || l < 0 || r >= n) return std::numeric_limits<T>::max();
        int j = bin_log[r - l + 1];
        return std::min(st_min[j][l], st_min[j][r - (1 << j) + 1]);
    }

    T queryMax(int l, int r) const {
        if (st_max.empty() || l > r || l < 0 || r >= n) return std::numeric_limits<T>::lowest();
        int j = bin_log[r - l + 1];
        return std::max(st_max[j][l], st_max[j][r - (1 << j) + 1]);
    }

    T queryGcd(int l, int r) const {
        if (st_gcd.empty() || l > r || l < 0 || r >= n) return 0;
        int j = bin_log[r - l + 1];
        return custom_gcd(st_gcd[j][l], st_gcd[j][r - (1 << j) + 1]);
    }

    T queryLcm(int l, int r) const {
        if (st_lcm.empty() || l > r || l < 0 || r >= n) return 1;
        int j = bin_log[r - l + 1];
        return custom_lcm(st_lcm[j][l], st_lcm[j][r - (1 << j) + 1]);
    }

    T queryAnd(int l, int r) const {
        if (st_and.empty() || l > r || l < 0 || r >= n) return ~(T)0;
        int j = bin_log[r - l + 1];
        return st_and[j][l] & st_and[j][r - (1 << j) + 1];
    }

    T queryOr(int l, int r) const {
        if (st_or.empty() || l > r || l < 0 || r >= n) return 0;
        int j = bin_log[r - l + 1];
        return st_or[j][l] | st_or[j][r - (1 << j) + 1];
    }
};


void solve() {
    int n, m, k; cin >> n >> m >> k;
    vector<int> a(n), b(m); scan_numbers(a); scan_numbers(b);
    sort(all(a));
    sort(all(b));

    int ans = 0, i = 0, j = 0;

    while (i < n and j < m) {
        if (b[j] - k > a[i]) i++;
        else if (b[j] + k < a[i]) j++;
        else i++, j++, ans++;
    }

    cout << ans << newl;
}

