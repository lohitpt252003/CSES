template <typename T, typename Op>
class SparseTable {
public:
    int n, log_max;
    std::vector<std::vector<T>> st;
    std::vector<int> bin_log;
    Op op;

    SparseTable(const std::vector<T>& a) {
        n = a.size();
        if (n == 0) return;
        
        bin_log.assign(n + 1, 0);
        for (int i = 2; i <= n; i++) bin_log[i] = bin_log[i / 2] + 1;
        
        log_max = bin_log[n] + 1;
        st.assign(log_max, std::vector<T>(n));
        
        for (int i = 0; i < n; i++) st[0][i] = a[i];
        
        for (int j = 1; j < log_max; j++) {
            for (int i = 0; i + (1 << j) <= n; i++) st[j][i] = op(st[j - 1][i], st[j - 1][i + (1 << (j - 1))]);
        }
    }

    T query(int l, int r) const {
        if (l > r or l < 0 or r >= n) return op.id();
        int j = bin_log[r - l + 1];
        return op(st[j][l], st[j][r - (1 << j) + 1]);
    }
};


template <typename T, typename Op>
class SegTree {
public:
    int n;
    std::vector<T> tree;
    Op op;

    SegTree(int n) : n(n), tree(2 * n, op.id()) {}

    SegTree(const std::vector<T>& a) {
        n = a.size();
        tree.assign(2 * n, op.id());
        build(a);
    }

    void build(const std::vector<T>& a) {
        for (int i = 0; i < n; i++) tree[n + i] = a[i];
        for (int i = n - 1; i > 0; --i) tree[i] = op(tree[i << 1], tree[i << 1 | 1]);
    }
    
    void update(int pos, T value) {
        for (tree[pos += n] = value; pos > 1; pos >>= 1) tree[pos >> 1] = op(tree[pos], tree[pos ^ 1]);
    }
    
    T query(int l, int r) const { 
        if (l > r or l < 0 or r >= n) return op.id();
        T resL = op.id(), resR = op.id();
        for (l += n, r += n + 1; l < r; l >>= 1, r >>= 1) {
            if (l & 1) resL = op(resL, tree[l++]);
            if (r & 1) resR = op(tree[--r], resR);
        }
        return op(resL, resR);
    }
};



template <typename T, typename Op, typename L = T>
class LazySegTree {
public:
    int n;
    std::vector<T> tree;
    std::vector<L> lazy;
    std::vector<bool> has_lazy;
    Op op;

    LazySegTree(int n) : n(n), tree(4 * n, op.tree_id()), lazy(4 * n), has_lazy(4 * n, false) {}

    LazySegTree(const std::vector<T>& a) : LazySegTree(a.size()) {
        if (n > 0) build(a, 1, 0, n - 1);
    }

    void build(const std::vector<T>& a, int node, int start, int end) {
        if (start == end) {
            tree[node] = a[start];
            return;
        }
        int mid = (start + end) / 2;
        build(a, 2 * node, start, mid);
        build(a, 2 * node + 1, mid + 1, end);
        tree[node] = op.merge_tree(tree[2 * node], tree[2 * node + 1]);
    }

    void apply(int node, int start, int end, L val) {
        tree[node] = op.apply_lazy(tree[node], val, end - start + 1);
        if (has_lazy[node]) lazy[node] = op.merge_lazy(lazy[node], val);
        else {
            lazy[node] = val;
            has_lazy[node] = true;
        }
    }

    void push(int node, int start, int end) {
        if (has_lazy[node]) {
            int mid = (start + end) / 2;
            apply(2 * node, start, mid, lazy[node]);
            apply(2 * node + 1, mid + 1, end, lazy[node]);
            has_lazy[node] = false;
        }
    }

    void update(int node, int start, int end, int l, int r, L val) {
        if (r < start or end < l) return;
        if (l <= start and end <= r) {
            apply(node, start, end, val);
            return;
        }
        push(node, start, end);
        int mid = (start + end) / 2;
        update(2 * node, start, mid, l, r, val);
        update(2 * node + 1, mid + 1, end, l, r, val);
        tree[node] = op.merge_tree(tree[2 * node], tree[2 * node + 1]);
    }

    void update(int l, int r, L val) {
        if (l > r or l < 0 or r >= n) return;
        update(1, 0, n - 1, l, r, val);
    }

    T query(int node, int start, int end, int l, int r) {
        if (r < start or end < l) return op.tree_id();
        if (l <= start and end <= r) return tree[node];
        push(node, start, end);
        int mid = (start + end) / 2;
        return op.merge_tree(query(2 * node, start, mid, l, r), query(2 * node + 1, mid + 1, end, l, r));
    }

    T query(int l, int r) {
        if (l > r or l < 0 or r >= n) return op.tree_id();
        return query(1, 0, n - 1, l, r);
    }
};


struct Node { ll sum, mn, mx; };
struct Update { bool is_set; ll val; };

struct Lazy_Mixed {
    Node merge_tree(Node a, Node b) const {
        if (a.mn == ll_INF) return b; 
        if (b.mn == ll_INF) return a;
        return {a.sum + b.sum, min(a.mn, b.mn), max(a.mx, b.mx)};
    }
    Update merge_lazy(Update old_lazy, Update new_lazy) const {
        if (new_lazy.is_set) return new_lazy;
        return {old_lazy.is_set, old_lazy.val + new_lazy.val};
    }
    Node apply_lazy(Node tree_val, Update lazy_val, int len) const {
        if (lazy_val.is_set) return {lazy_val.val * len, lazy_val.val, lazy_val.val};
        else return {tree_val.sum + lazy_val.val * len, tree_val.mn + lazy_val.val, tree_val.mx + lazy_val.val};
    }
    Node tree_id() const { return {0, ll_INF, -ll_INF}; } 
};

class MixedSegTree : public LazySegTree<Node, Lazy_Mixed, Update> {
private:
    static vector<Node> convert(const vector<ll>& a) {
        vector<Node> init(a.size());
        for (size_t i = 0; i < a.size(); i++) init[i] = {a[i], a[i], a[i]};
        return init;
    }

public:
    MixedSegTree(const vector<ll>& a) : LazySegTree<Node, Lazy_Mixed, Update>(convert(a)) {}

    void add(int l, int r, ll val) { update(l, r, {false, val}); }
    void set_val(int l, int r, ll val) { update(l, r, {true, val}); }
    
    ll querySum(int l, int r) { return query(l, r).sum; }
    ll queryMin(int l, int r) { return query(l, r).mn; }
    ll queryMax(int l, int r) { return query(l, r).mx; }
};


